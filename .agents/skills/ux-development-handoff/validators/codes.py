SEVERITY = {
    ORPHAN_SCREEN: FAILED, ORPHAN_STITCH_ARTIFACT: FAILED, MISSING_FLOW_REFERENCE: BLOCKED,
    MISSING_REQUIREMENT_LINEAGE: BLOCKED, MULTIPLE_ACTIVE_STITCH_PROJECTS: FAILED,
    WRONG_STITCH_PROJECT: FAILED, STALE_STITCH_REFERENCE: FAILED, STALE_FIGMA_REFERENCE: FAILED,
    STITCH_FIGMA_DIVERGENCE: BLOCKED, MISSING_GOVERNED_DESIGN: BLOCKED, MISSING_SCREEN_STATE: FAILED,
    MISSING_RESPONSIVE_RULE: FAILED, MISSING_ACCESSIBILITY_REQUIREMENT: FAILED,
    MISSING_COMPONENT_REFERENCE: FAILED, MISSING_TOKEN_REFERENCE: FAILED, BLOCKING_OPEN_QUESTION: BLOCKED,
    MISSING_INITIATIVE: BLOCKED, MISSING_STITCH_PROJECT: BLOCKED, DANGLING_REFERENCE: FAILED,
    DUPLICATE_ID: FAILED, PLACEHOLDER_REFERENCE: BLOCKED, HUMAN_REVIEW_PENDING: BLOCKED,
    OKF_INVALID: FAILED, MISSING_HANDOFF: BLOCKED, MISSING_HANDOFF_SECTION: FAILED,
    INVALID_ARTIFACT_REF: FAILED, UNVERIFIED_ARTIFACT_REF: BLOCKED,
}


@dataclass(frozen=True)
class Finding:
    code: str
    subject: str
    message: str

    @property
    def severity(self) -> str:
        return SEVERITY[self.code]

    def as_dict(self) -> dict:
        return {"code": self.code, "subject": self.subject, "severity": self.severity, "message": self.message}


def overall(findings) -> str:
    """FAILED prevails over BLOCKED; no findings means PASSED."""
    sev = {f.severity for f in findings}
    return FAILED if FAILED in sev else BLOCKED if BLOCKED in sev else PASSED
