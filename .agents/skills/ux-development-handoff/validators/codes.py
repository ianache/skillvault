STALE_FIGMA_REFERENCE = "STALE_FIGMA_REFERENCE"
STITCH_FIGMA_DIVERGENCE = "STITCH_FIGMA_DIVERGENCE"
MISSING_GOVERNED_DESIGN = "MISSING_GOVERNED_DESIGN"
MISSING_SCREEN_STATE = "MISSING_SCREEN_STATE"
MISSING_RESPONSIVE_RULE = "MISSING_RESPONSIVE_RULE"
